/**
 * @param {number} packed
 */
function decodeItemPos(packed) {
  return {
    x: packed & 0xf0,
    y: (packed & 0x0f) << 4,
    packed,
  };
}

/**
 * Apply Q2 LevelInfo replacement fields onto a built level object.
 * Mutates and returns `level`.
 * @param {object} level
 */
export function applyQuest2LevelInfo(level) {
  if (!level || level.quest !== 2) return level;
  const idx = (level.level ?? 0) - 1;
  const bytes = Q2_LEVEL_INFO_REPLACEMENTS[idx];
  if (!bytes?.length) return level;

  level.itemPositions = bytes.slice(OFF.ITEM_POS, OFF.ITEM_POS + 4).map(decodeItemPos);
  if (bytes[OFF.SUBMENU_ROT] != null) level.submenuMapRotation = bytes[OFF.SUBMENU_ROT];
  level.startRoom = bytes[OFF.START_ROOM];
  level.triforceRoom = bytes[OFF.TRIFORCE_ROOM];
  level.bossRoom = bytes[OFF.BOSS_ROOM];
  const cellars = bytes.slice(OFF.CELLARS, OFF.CELLARS + 10);
  level.cellarRooms = cellars.filter((r) => r !== 0xff);
  if (bytes.length >= OFF.DRAWN_MAP + 16) {
    level.drawnMap = [...bytes.slice(OFF.DRAWN_MAP, OFF.DRAWN_MAP + 16)];
  }
  return level;
}
