/**
 * Link damage from ObjTypeToDamagePoints (Z_01.asm HarmLink).
 *
 * NES packs damage as one byte per object type:
 *   low nibble  → full hearts subtracted from HeartValues
 *   high nibble → HeartPartial delta ($80 ≈ half a heart)
 *
 * Our inventory uses half-hearts (2 = one full heart).
 */

/** Captured from USA PRG1 ObjTypeToDamagePoints. */
export const OBJ_DAMAGE_BYTES = Object.freeze([
  0x60, 0x02, 0x01, 0x80, 0x80, 0x01, 0x80, 0x80, // $00–$07
  0x80, 0x80, 0x80, 0x01, 0x02, 0x80, 0x80, 0x01, // $08–$0F
  0x80, 0x80, 0x01, 0x01, 0x80, 0x80, 0x02, 0x01, // $10–$17
  0x02, 0x00, 0x80, 0x80, 0x80, 0x80, 0x01, 0x80, // $18–$1F
  0x80, 0x01, 0x01, 0x02, 0x01, 0x02, 0x02, 0x80, // $20–$27
  0x80, 0x80, 0x80, 0x00, 0x00, 0x00, 0x00, 0x00, // $28–$2F
  0x02, 0x01, 0x01, 0x02, 0x02, 0x00, 0x00, 0x00, // $30–$37
  0x02, 0x02, 0x02, 0x02, 0x01, 0x01, 0x04, 0x80, // $38–$3F
  0x80, 0x80, 0x01, 0x01, 0x01, 0x01, 0x01, 0x02, // $40–$47
  0x02, 0x01, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, // $48–$4F
  0x00, 0x00, 0x00, 0x80, 0x80, 0x80, 0x01, 0x02, // $50–$57
  0x02, 0x04, 0x04, 0x80, 0x01, // $58–$5C
]);

/**
 * @param {number} byte ObjTypeToDamagePoints entry
 * @returns {number} damage in half-hearts (0 = no damage)
 */
export function damageByteToHalfHearts(byte) {
  const b = byte & 0xff;
  if (b === 0) return 0;
  const fullHearts = b & 0x0f;
  const partial = b & 0xf0;
  let half = fullHearts * 2;
  // $80 is the common "half heart" packing; smaller partials ($60) still hurt.
  if (partial > 0) half += 1;
  return half;
}

/**
 * Contact / shot damage for an object type, in half-hearts.
 * @param {number} objType
 */
export function damageHalfHeartsForType(objType) {
  const byte = OBJ_DAMAGE_BYTES[objType & 0xff] ?? 0x80;
  return damageByteToHalfHearts(byte);
}
